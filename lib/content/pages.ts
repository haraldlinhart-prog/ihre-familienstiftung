export function getTopic(slug: string): TopicPage | undefined {
  return topicPages.find((page) => page.slug === slug);
}

export function requireTopic(slug: string): TopicPage {
  const page = getTopic(slug);
  if (!page) throw new Error(`Seite fehlt: ${slug}`);
  return page;
}
